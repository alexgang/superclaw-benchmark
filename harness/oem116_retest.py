"""Retest the 53 OEM PinchBench cases that failed in the 2026-08-27 run.

Inputs:
  retest_kit/retest_kit/retest_tasks.json     (generated by build_retest_plan.py)
  retest_kit/retest_kit/RETEST_PLAN.md        (the plan)

Driver:
  harness/lh_automation.py                    (already supports --timeout, --save-raw,
                                              --tasks, --out; outputs to results/v4_raw/<arm>/<task_id>/)

Differences from oem116_rerun.py (the full 116 rerun):
  - Only the 53 task indices that hit the 240s cap or got contaminated
  - Timeout bumped to 1800s (per user request, 2026-08-28)
  - Output jsonl is SEPARATE (oem_retest53_pw085.jsonl) so A-side can diff cleanly
  - arm-label = oem_retest (so save-raw writes to results/v4_raw/oem_retest/<task_id>/)

Known limitation (per RETEST_PLAN.md section 3, fix #1):
  lh_automation.py does NOT terminate the SuperClaw session on per-task timeout,
  so cross-task contamination can still happen. Each 1800s timeout window
  leaves a residual writing window.  We proceed because the user requested
  the 1800s bump; residual risk is logged in RETEST_PLAN.md risk note.
"""
import argparse
import json
import os
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(r'C:\Users\Trekker-PTL\superclaw_benchmark')
LOGS = ROOT / 'logs'
RETEST_KIT = ROOT / 'retest_kit' / 'retest_kit'
TASKS_FILE = ROOT / 'tasks' / 'tasks_pinchbench_oem.jsonl'

PY = r'C:\Users\Trekker-PTL\miniforge3\python.exe'
HARNESS = ROOT / 'harness' / 'lh_automation.py'

ARM = {'model': 'auto', 'label': 'oem_retest', 'pw': 0.85}
OUT = LOGS / 'oem_retest53_pw085.jsonl'

# 53 retest task indices from build_retest_plan.py / RETEST_PLAN.md / retest_tasks.json
TASKS_ARG = (
    '9,11,14,15,17,20,25,26,30,31,32,33,35,38,39,44,46,47,48,49,50,51,52,60,61,62,63,65,'
    '66,67,68,69,71,72,74,75,77,81,82,83,84,88,90,92,96,101,104,106,109,111,112,113,115'
)
TIMEOUT_S = 1800  # user-requested cap (RETEST_PLAN.md recommends 600, user said 1800)

_ap = argparse.ArgumentParser(add_help=False)
_ap.add_argument('--start-from', type=int, default=0,
                 help='First task INDEX in TASKS_ARG to run (for resume).')
_ap.add_argument('--dry-run', action='store_true',
                 help='Print the command without running it.')
_args, _rest = _ap.parse_known_args()
START_FROM = _args.start_from

# Parse TASKS_ARG into a list, slice by START_FROM
_all_indices = [int(x) for x in TASKS_ARG.split(',')]
indices = _all_indices[START_FROM:]

print(f'OEM PinchBench RETEST (53 cases) — auto, pw=0.85')
print(f'  total in plan:     {len(_all_indices)}')
print(f'  start_from offset: {START_FROM} (resuming from index {START_FROM} of the 53)')
print(f'  will run:          {len(indices)} task indices')
print(f'  python:            {PY}')
print(f'  harness:           {HARNESS.name}')
print(f'  output:            {OUT.name}')
print(f'  arm-label:         {ARM["label"]}  (so save-raw -> results/v4_raw/oem_retest/<task_id>/)')
print(f'  timeout:           {TIMEOUT_S}s/task (user-requested; plan recommends 600s)')
print(f'  estimated wall:    ~{len(indices) * 6 / 60:.1f}h (assuming mean ~6 min/task;'
      f' worst case {len(indices) * TIMEOUT_S / 3600:.1f}h)')
print(f'  retest_plan:       {RETEST_KIT / "RETEST_PLAN.md"}')
print()

# Refuse to silently overwrite; user must pass --start-from or delete the file
if OUT.exists() and START_FROM == 0:
    n_existing = sum(1 for line in OUT.read_text(encoding='utf-8').splitlines() if line.strip())
    print(f'NOTE: {OUT.name} already exists with {n_existing} rows.')
    print(f'  Refusing to start from scratch (would duplicate rows).')
    print(f'  Use --start-from {n_existing} to resume, or delete the file.')
    sys.exit(1)
elif OUT.exists() and START_FROM > 0:
    n_existing = sum(1 for line in OUT.read_text(encoding='utf-8').splitlines() if line.strip())
    print(f'NOTE: {OUT.name} already has {n_existing} rows; resuming from --start-from {START_FROM}.')

# Build command. --save-raw so deliverable bodies land in results/v4_raw/oem_retest/<task_id>/
# (lh_automation implements this; see harness/lh_automation.py around line 1394.)
cmd = [
    PY, str(HARNESS),
    '--perf-weight', str(ARM['pw']),
    '--model', ARM['model'],
    '--arm-label', ARM['label'],
    '--save-raw',
    '--timeout', str(TIMEOUT_S),
    '--tasks', ','.join(str(i) for i in indices),
    '--out', str(OUT),
]
env = os.environ.copy()
env.pop('HTTP_PROXY', None)
env.pop('HTTPS_PROXY', None)
env['LH_TASKS_FILE'] = str(TASKS_FILE)

print(f'cmd: {" ".join(cmd[:6])} ... (truncated)')
print(f'env: LH_TASKS_FILE={TASKS_FILE.name}, HTTP(S)_PROXY unset')
print()
print(f'task list: {",".join(str(i) for i in indices)}')
print()

if _args.dry_run:
    print('--- DRY RUN: not executing ---')
    print('Full command:')
    print(' '.join(repr(c) for c in cmd))
    sys.exit(0)

print(f'starting at {time.strftime("%Y-%m-%d %H:%M:%S")} ...')
t0 = time.time()
result = subprocess.run(cmd, env=env, cwd=str(ROOT))
elapsed = time.time() - t0
print(f'\nexit={result.returncode}, elapsed={elapsed:.1f}s ({elapsed/3600:.2f}h)')

# Summarize
if OUT.exists():
    rows = [json.loads(l) for l in OUT.read_text(encoding='utf-8').splitlines() if l.strip()]
    print(f'\n=== {OUT.name}: {len(rows)} rows ===')
    if rows:
        from scoring import score_of, summarize
        print(summarize(rows, 'overall'))
        graded = [(r['task_id'], score_of(r)) for r in rows if score_of(r) is not None]
        zero = [(t, s) for t, s in graded if s == 0.0]
        print(f'\ngraded: {len(graded)}    still-zero after retest: {len(zero)}')
        if zero:
            print('  still-zero (route/local model problem; not timeout):')
            for t, _ in zero:
                print(f'    {t}')
